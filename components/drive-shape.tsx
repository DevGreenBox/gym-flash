import { SPEC } from "@/lib/site";

/**
 * Силуэт корпуса — снят с чертежа заказчика пиксель в пиксель.
 *
 * Замер `assets/image 18.png`: корпус 287 × 99 px на 49,96 × 17 мм,
 * то есть 5,75 px/мм. Верх и низ идут ровной прямой от 282 до 532 px —
 * это плоские грани. Торцы выпирают ровно на 15 px = 2,6 мм и достигают
 * крайней точки на середине высоты. Значит торец — не полукруг
 * (радиус был бы 8,5 мм) и не скруглённый угол, а эллиптическая дуга:
 * 2,6 мм по горизонтали на 8,5 мм по вертикали.
 *
 * Такая же форма на фотографии партии — «подушка», а не капсула.
 *
 * Ширина колпачка замерена по той же фотографии: пластина 195 px
 * на 50 мм даёт 3,90 px/мм, чёрное слева — 5,4 мм.
 */
/**
 * Разъём USB. Флешка поворотная: цветная оболочка — внешняя часть,
 * чёрный разъём сидит внутри неё и выходит слева, а не приставлен
 * к торцу бруском, как было раньше.
 *
 * Вылет 4,7 мм — решение заказчика от 27.08. По крупному снимку
 * выходило 11 мм (68 px при 6,14 px/мм), по фотографии партии —
 * 3,1 мм (71 px при 23,04 px/мм по длине). Заказчик выбрал середину
 * ближе к партии; подбирать заново не нужно, число задано.
 *
 * Высота и нос — с крупного снимка, он снят в лоб: 15,4 мм при
 * корпусе 17 и нос 3,0 мм.
 */
const USB_ВЫЛЕТ = 4.7;
const USB_ПОЛЕ = 0.8;
const USB_НОС = 3;

/**
 * Левый предел надписи. На изделии «Ч» начинается примерно в 5,4 мм
 * от торца оболочки — дальше скруглённый нос, гравировать там нечего.
 * Число замерено по той же фотографии.
 */
export const ОТСТУП_НАДПИСИ = 5.4;

/** Вылет торца оболочки по горизонтали. */
const КРАЙ = 2.6;
const ПОЛЕ = 1;

export const ПЛАСТИНА_X = ПОЛЕ + USB_ВЫЛЕТ;
export const ПЛАСТИНА_Y = ПОЛЕ;

/**
 * Подвеска: ушко в торце, короткая змейка и заводное кольцо.
 * Размеры сняты с фотографии партии по длине оболочки.
 */
const УШКО_R = 1.9;
const ЦЕПЬ_Д = 10;
const КОЛЬЦО_R = 6.5;
const КОЛЬЦО_Т = 1.15;
/** Насколько подвеска выходит за правый торец оболочки. */
const ПОДВЕС = 1 + УШКО_R + ЦЕПЬ_Д + КОЛЬЦО_R * 2 + КОЛЬЦО_Т / 2 + 1;

/**
 * Холст под флешку — ровно по нарисованному, поле в миллиметр
 * со всех сторон. Слева к оболочке добавляется вылет разъёма,
 * справа — подвеска, если её показывают.
 */
export const ХОЛСТ = (chain = false) => ({
  w: USB_ВЫЛЕТ + SPEC.plate + ПОЛЕ * 2 + (chain ? ПОДВЕС : 0),
  h: SPEC.plateH + ПОЛЕ * 2,
});

/** Доли корпуса внутри холста — по ним кладутся зоны нажатия. */
export const ПЛАСТИНА_ДОЛИ = (chain = false) => {
  const холст = ХОЛСТ(chain);
  return {
    left: (ПЛАСТИНА_X / холст.w) * 100,
    top: (ПЛАСТИНА_Y / холст.h) * 100,
    width: (SPEC.plate / холст.w) * 100,
    height: (SPEC.plateH / холст.h) * 100,
  };
};

/** Контур корпуса: прямые верх и низ, торцы — эллиптические дуги. */
export const КОРПУС_D = (() => {
  const x = ПЛАСТИНА_X;
  const y = ПЛАСТИНА_Y;
  const w = SPEC.plate;
  const h = SPEC.plateH;
  const ry = h / 2;
  return [
    `M ${x + КРАЙ} ${y}`,
    `H ${x + w - КРАЙ}`,
    `A ${КРАЙ} ${ry} 0 0 1 ${x + w - КРАЙ} ${y + h}`,
    `H ${x + КРАЙ}`,
    `A ${КРАЙ} ${ry} 0 0 1 ${x + КРАЙ} ${y}`,
    "Z",
  ].join(" ");
})();

/**
 * Чёрный разъём. Рисуется под оболочкой, поэтому виден только его вылет:
 * оболочка накрывает остальное своим скруглённым носом — ровно тот стык,
 * что видно на изделии. Форма та же, что у корпуса: прямые верх и низ,
 * торец эллиптической дугой.
 */
export function DriveUSB({ uid }: { uid: string }) {
  const x = ПЛАСТИНА_X - USB_ВЫЛЕТ;
  const y = ПЛАСТИНА_Y + USB_ПОЛЕ;
  const h = SPEC.plateH - USB_ПОЛЕ * 2;
  const ry = h / 2;
  /* правый край уводим глубоко под оболочку — там он всё равно скрыт */
  const x1 = ПЛАСТИНА_X + 8;
  const d = [
    `M ${x + USB_НОС} ${y}`,
    `H ${x1}`,
    `V ${y + h}`,
    `H ${x + USB_НОС}`,
    `A ${USB_НОС} ${ry} 0 0 1 ${x + USB_НОС} ${y}`,
    "Z",
  ].join(" ");

  return (
    <>
      <defs>
        <linearGradient id={`${uid}-usb`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor="#4a4a4d" />
          <stop offset="38%" stopColor="#292a2c" />
          <stop offset="100%" stopColor="#141416" />
        </linearGradient>
      </defs>
      <path d={d} fill={`url(#${uid}-usb)`} />
    </>
  );
}

/**
 * Подвеска. На фотографии партии это ушко в торце оболочки, короткая
 * змейка и заводное кольцо, всё стальное. Показывается только там,
 * где смотрят на изделие целиком: в шаге «Результат» и на витрине.
 * В рабочем превью её нет намеренно — она съедает треть ширины,
 * а править надо гравировку.
 */
export function DriveChain({ uid }: { uid: string }) {
  const cy = ПЛАСТИНА_Y + SPEC.plateH / 2;
  const ушкоX = ПЛАСТИНА_X + SPEC.plate + 1;
  const кольцоX = ушкоX + УШКО_R + ЦЕПЬ_Д + КОЛЬЦО_R;
  const цепьX0 = ушкоX + УШКО_R - 0.3;
  const цепьX1 = кольцоX - КОЛЬЦО_R + 0.3;
  /* Змейка провисает: прямая палка читается стержнем, а на фотографии
     цепочка лежит на столе и провисает между ушком и кольцом. */
  const провис = 2;
  const цепь = `M ${цепьX0} ${cy} Q ${(цепьX0 + цепьX1) / 2} ${cy + провис * 2} ${цепьX1} ${cy}`;

  return (
    <>
      <defs>
        {/* Сталь: блик по верхней трети, тень книзу — иначе металл
            читается серой заливкой. */}
        <linearGradient id={`${uid}-steel`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor="#f4f4f6" />
          <stop offset="26%" stopColor="#d9d9de" />
          <stop offset="54%" stopColor="#8e8e95" />
          <stop offset="78%" stopColor="#b8b8bf" />
          <stop offset="100%" stopColor="#6f6f76" />
        </linearGradient>
      </defs>

      {/* Змейка */}
      <path
        d={цепь}
        fill="none"
        stroke={`url(#${uid}-steel)`}
        strokeWidth="1.7"
        strokeLinecap="round"
      />
      <path
        d={цепь}
        fill="none"
        stroke="#5f5f66"
        strokeOpacity="0.5"
        strokeWidth="1.7"
        strokeLinecap="round"
        strokeDasharray="0.22 0.85"
      />

      {/* Ушко в торце: половина уходит под оболочку */}
      <circle
        cx={ушкоX}
        cy={cy}
        r={УШКО_R}
        fill="none"
        stroke={`url(#${uid}-steel)`}
        strokeWidth="0.72"
      />

      {/* Заводное кольцо: второй виток проволоки — тем и отличается
          от простого колечка */}
      <circle
        cx={кольцоX}
        cy={cy}
        r={КОЛЬЦО_R}
        fill="none"
        stroke={`url(#${uid}-steel)`}
        strokeWidth={КОЛЬЦО_Т}
      />
      <path
        d={`M ${кольцоX - КОЛЬЦО_R - КОЛЬЦО_Т * 0.5} ${cy}
            A ${КОЛЬЦО_R + КОЛЬЦО_Т * 0.5} ${КОЛЬЦО_R + КОЛЬЦО_Т * 0.5} 0 0 1 ${кольцоX + КОЛЬЦО_R * 0.72} ${cy - КОЛЬЦО_R * 0.7}`}
        fill="none"
        stroke={`url(#${uid}-steel)`}
        strokeWidth={КОЛЬЦО_Т * 0.8}
        strokeLinecap="round"
      />
    </>
  );
}

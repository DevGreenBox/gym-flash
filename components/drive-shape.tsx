import { SPEC } from "@/lib/site";

/**
 * Силуэт корпуса — снят с чертежа заказчика пиксель в пиксель.
 *
 * Замер `assets/image 18.png`: корпус 287 × 99 px на 49,96 × 17 мм,
 * то есть 5,75 px/мм. Верх и низ идут ровной прямой от 282 до 532 px —
 * это плоские грани. Торцы выпирают ровно на 15 px = 2,6 мм и достигают
 * крайней точки на середине высоты. Значит торец — не полукруг
 * (радиус был бы 8,5 мм) и не скруглённый угол, а эллиптическая дуга:
 * 2,6 мм по горизонтали на 8,5 мм по вертикали.
 *
 * Такая же форма на фотографии партии — «подушка», а не капсула.
 *
 * Ширина колпачка замерена по той же фотографии: пластина 195 px
 * на 50 мм даёт 3,90 px/мм, чёрное слева — 5,4 мм.
 */
/**
 * Разъём USB. Флешка поворотная: цветная оболочка — внешняя часть,
 * чёрный разъём сидит внутри неё и выходит слева, а не приставлен
 * к торцу бруском, как было раньше.
 *
 * Вылет 4,7 мм — решение заказчика от 27.08. По крупному снимку
 * выходило 11 мм (68 px при 6,14 px/мм), по фотографии партии —
 * 3,1 мм (71 px при 23,04 px/мм по длине). Заказчик выбрал середину
 * ближе к партии; подбирать заново не нужно, число задано.
 *
 * Высота и нос — с крупного снимка, он снят в лоб: 15,4 мм при
 * корпусе 17 и нос 3,0 мм.
 */
const USB_ВЫЛЕТ = 4.7;
const USB_ПОЛЕ = 0.8;
const USB_НОС = 3;

/**
 * Левый предел надписи. На изделии «Ч» начинается примерно в 5,4 мм
 * от торца оболочки — дальше скруглённый нос, гравировать там нечего.
 * Число замерено по той же фотографии.
 */
export const ОТСТУП_НАДПИСИ = 5.4;

/** Вылет торца оболочки по горизонтали. */
const КРАЙ = 2.6;
const ПОЛЕ = 1;

export const ПЛАСТИНА_X = ПОЛЕ + USB_ВЫЛЕТ;
export const ПЛАСТИНА_Y = ПОЛЕ;

/**
 * Подвеска — по крупному снимку заказчика от 27.08. Собрана из тех же
 * частей, что на изделии: ушко в торце, короткий стержень, витая пружина
 * в двух обоймах, каплевидная дужка и заводное кольцо.
 *
 * Масштаб снимка: корпус 55 px на 17 мм даёт 3,24 px/мм. Длины частей
 * сняты по нему и слегка поджаты — в натуральную величину подвеска длиннее
 * самой флешки, и в окне превью от гравировки ничего бы не осталось.
 */
const УШКО_R = 1.9;
const СТЕРЖЕНЬ = 4.2;
const ОБОЙМА = 1.7;
const ПРУЖИНА = 13;
const ДУЖКА_Д = 8;
const ДУЖКА_В = 5.6;
const КОЛЬЦО_R = 8.6;
const КОЛЬЦО_Т = 0.85;
/** Насколько подвеска выходит за правый торец оболочки. */
const ПОДВЕС =
  1 + УШКО_R + СТЕРЖЕНЬ + ОБОЙМА * 2 + ПРУЖИНА + ДУЖКА_Д + КОЛЬЦО_R * 2 + 1;

/**
 * Холст под флешку — ровно по нарисованному, поле в миллиметр
 * со всех сторон. Слева к оболочке добавляется вылет разъёма,
 * справа — подвеска, если её показывают.
 */
export const ХОЛСТ = (chain = false) => ({
  w: USB_ВЫЛЕТ + SPEC.plate + ПОЛЕ * 2 + (chain ? ПОДВЕС : 0),
  h: SPEC.plateH + ПОЛЕ * 2,
});

/** Доли корпуса внутри холста — по ним кладутся зоны нажатия. */
export const ПЛАСТИНА_ДОЛИ = (chain = false) => {
  const холст = ХОЛСТ(chain);
  return {
    left: (ПЛАСТИНА_X / холст.w) * 100,
    top: (ПЛАСТИНА_Y / холст.h) * 100,
    width: (SPEC.plate / холст.w) * 100,
    height: (SPEC.plateH / холст.h) * 100,
  };
};

/** Контур корпуса: прямые верх и низ, торцы — эллиптические дуги. */
export const КОРПУС_D = (() => {
  const x = ПЛАСТИНА_X;
  const y = ПЛАСТИНА_Y;
  const w = SPEC.plate;
  const h = SPEC.plateH;
  const ry = h / 2;
  return [
    `M ${x + КРАЙ} ${y}`,
    `H ${x + w - КРАЙ}`,
    `A ${КРАЙ} ${ry} 0 0 1 ${x + w - КРАЙ} ${y + h}`,
    `H ${x + КРАЙ}`,
    `A ${КРАЙ} ${ry} 0 0 1 ${x + КРАЙ} ${y}`,
    "Z",
  ].join(" ");
})();

/**
 * Чёрный разъём. Рисуется под оболочкой, поэтому виден только его вылет:
 * оболочка накрывает остальное своим скруглённым носом — ровно тот стык,
 * что видно на изделии. Форма та же, что у корпуса: прямые верх и низ,
 * торец эллиптической дугой.
 */
export function DriveUSB({ uid }: { uid: string }) {
  const x = ПЛАСТИНА_X - USB_ВЫЛЕТ;
  const y = ПЛАСТИНА_Y + USB_ПОЛЕ;
  const h = SPEC.plateH - USB_ПОЛЕ * 2;
  const ry = h / 2;
  /* правый край уводим глубоко под оболочку — там он всё равно скрыт */
  const x1 = ПЛАСТИНА_X + 8;
  const d = [
    `M ${x + USB_НОС} ${y}`,
    `H ${x1}`,
    `V ${y + h}`,
    `H ${x + USB_НОС}`,
    `A ${USB_НОС} ${ry} 0 0 1 ${x + USB_НОС} ${y}`,
    "Z",
  ].join(" ");

  return (
    <>
      <defs>
        <linearGradient id={`${uid}-usb`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor="#4a4a4d" />
          <stop offset="38%" stopColor="#292a2c" />
          <stop offset="100%" stopColor="#141416" />
        </linearGradient>
      </defs>
      <path d={d} fill={`url(#${uid}-usb)`} />
    </>
  );
}

/**
 * Подвеска. Показывается только там, где смотрят на изделие целиком:
 * в шаге «Результат». В рабочем превью её нет намеренно — она длиннее
 * самой флешки, а править надо гравировку.
 */
export function DriveChain({ uid }: { uid: string }) {
  const cy = ПЛАСТИНА_Y + SPEC.plateH / 2;
  const ушкоX = ПЛАСТИНА_X + SPEC.plate + 1;

  const стерженьX = ушкоX + УШКО_R - 0.2;
  const обойма1X = стерженьX + СТЕРЖЕНЬ;
  const пружинаX = обойма1X + ОБОЙМА;
  const обойма2X = пружинаX + ПРУЖИНА;
  const дужкаX = обойма2X + ОБОЙМА - 0.3;
  const кольцоX = дужкаX + ДУЖКА_Д - 1.8 + КОЛЬЦО_R;

  /* Витки пружины: наклонные штрихи поперёк капсулы. Ровные вертикальные
     читались бы насечкой, а на снимке видно именно спираль. */
  const витков = Math.round(ПРУЖИНА / 0.62);
  const шаг = ПРУЖИНА / витков;

  const обойма = (x: number) => (
    <g key={x}>
      <rect
        x={x}
        y={cy - 1.5}
        width={ОБОЙМА}
        height={3}
        rx={0.45}
        fill={`url(#${uid}-steel)`}
        stroke="#4a4b53"
        strokeOpacity="0.4"
        strokeWidth="0.12"
      />
      <rect
        x={x}
        y={cy - 1.5}
        width={ОБОЙМА}
        height={3}
        rx={0.45}
        fill={`url(#${uid}-gloss)`}
      />
    </g>
  );

  return (
    <>
      <defs>
        {/*
          Круглая проволока, освещённая сверху. Верхняя кромка темнее,
          в верхней трети — узкий блик, дальше тон ровно уходит в тень.
          Прежний вариант держал вторую светлую полосу внизу: так
          выглядит гранёный профиль, а на снимке проволока круглая.
        */}
        <linearGradient id={`${uid}-steel`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor="#9fa0a8" />
          <stop offset="16%" stopColor="#fafbfc" />
          <stop offset="30%" stopColor="#e2e3e8" />
          <stop offset="52%" stopColor="#b0b1b9" />
          <stop offset="74%" stopColor="#83848c" />
          <stop offset="100%" stopColor="#5a5b63" />
        </linearGradient>

        {/*
          Плоская проволока кольца: у неё блик в середине сечения,
          а тёмное — по обеим кромкам. Тем и отличается от круглой.
        */}
        <linearGradient id={`${uid}-steel-x`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor="#6c6d75" />
          <stop offset="18%" stopColor="#eceef2" />
          <stop offset="44%" stopColor="#fbfbfd" />
          <stop offset="68%" stopColor="#bdbec6" />
          <stop offset="88%" stopColor="#84858d" />
          <stop offset="100%" stopColor="#5c5d65" />
        </linearGradient>

        {/*
          Продольный блик. На снимке по всей подвеске идёт одна светлая
          полоса — она и связывает витки пружины в единую деталь, иначе
          они распадаются на отдельные штрихи.
        */}
        <linearGradient id={`${uid}-gloss`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor="#fff" stopOpacity="0" />
          <stop offset="17%" stopColor="#fff" stopOpacity="0.9" />
          <stop offset="31%" stopColor="#fff" stopOpacity="0" />
          <stop offset="100%" stopColor="#fff" stopOpacity="0" />
        </linearGradient>

        <clipPath id={`${uid}-coil`}>
          <rect
            x={пружинаX}
            y={cy - 1.35}
            width={ПРУЖИНА}
            height={2.7}
            rx={0.5}
          />
        </clipPath>
      </defs>

      {/* Ушко в торце: половина уходит под оболочку */}
      <circle
        cx={ушкоX}
        cy={cy}
        r={УШКО_R}
        fill="none"
        stroke={`url(#${uid}-steel)`}
        strokeWidth="0.7"
      />

      {/* Стержень между ушком и пружиной */}
      <rect
        x={стерженьX}
        y={cy - 0.45}
        width={СТЕРЖЕНЬ + 0.4}
        height={0.9}
        rx={0.45}
        fill={`url(#${uid}-steel)`}
      />
      <rect
        x={стерженьX}
        y={cy - 0.45}
        width={СТЕРЖЕНЬ + 0.4}
        height={0.9}
        rx={0.45}
        fill={`url(#${uid}-gloss)`}
      />

      {/* Пружина: капсула плюс наклонные витки */}
      <rect
        x={пружинаX}
        y={cy - 1.35}
        width={ПРУЖИНА}
        height={2.7}
        rx={0.5}
        fill={`url(#${uid}-steel)`}
      />
      {/* Витки: тонкие тёмные линии между оборотами. Толстые полосы
          превращали пружину в винтовую резьбу — на снимке навивка
          мелкая и общий тон светлый. */}
      <g clipPath={`url(#${uid}-coil)`} strokeLinecap="butt">
        {Array.from({ length: витков + 2 }, (_, i) => {
          const x = пружинаX + шаг * i;
          return (
            <line
              key={i}
              x1={x - 0.42}
              y1={cy + 1.5}
              x2={x + 0.42}
              y2={cy - 1.5}
              stroke="#3a3b43"
              strokeOpacity="0.5"
              strokeWidth="0.17"
            />
          );
        })}
      </g>
      {/* Общий блик поверх витков — им пружина и держится как одна деталь */}
      <rect
        x={пружинаX}
        y={cy - 1.35}
        width={ПРУЖИНА}
        height={2.7}
        rx={0.5}
        fill={`url(#${uid}-gloss)`}
      />

      {обойма(обойма1X)}
      {обойма(обойма2X)}

      {/* Дужка: каплей, узкой стороной к пружине */}
      <path
        d={`M ${дужкаX} ${cy}
            C ${дужкаX + ДУЖКА_Д * 0.28} ${cy - ДУЖКА_В / 2}
              ${дужкаX + ДУЖКА_Д * 0.72} ${cy - ДУЖКА_В / 2}
              ${дужкаX + ДУЖКА_Д} ${cy}
            C ${дужкаX + ДУЖКА_Д * 0.72} ${cy + ДУЖКА_В / 2}
              ${дужкаX + ДУЖКА_Д * 0.28} ${cy + ДУЖКА_В / 2}
              ${дужкаX} ${cy} Z`}
        fill="none"
        stroke={`url(#${uid}-steel-x)`}
        strokeWidth="0.85"
      />

      {/* Заводное кольцо: два витка плоской проволоки */}
      <circle
        cx={кольцоX}
        cy={cy}
        r={КОЛЬЦО_R}
        fill="none"
        stroke={`url(#${uid}-steel-x)`}
        strokeWidth={КОЛЬЦО_Т}
      />
      <circle
        cx={кольцоX}
        cy={cy}
        r={КОЛЬЦО_R - КОЛЬЦО_Т}
        fill="none"
        stroke={`url(#${uid}-steel-x)`}
        strokeWidth={КОЛЬЦО_Т}
      />
      {/* Ложбинка между витками: по ней кольцо и читается двойным */}
      <circle
        cx={кольцоX}
        cy={cy}
        r={КОЛЬЦО_R - КОЛЬЦО_Т / 2}
        fill="none"
        stroke="#3a3b43"
        strokeOpacity="0.55"
        strokeWidth="0.14"
      />
      {/* Блик по верхней дуге — то, чем полированная сталь отличается
          от матовой: свет собирается в одну короткую полосу. */}
      <path
        d={`M ${кольцоX - КОЛЬЦО_R * 0.72} ${cy - КОЛЬЦО_R * 0.7}
            a ${КОЛЬЦО_R} ${КОЛЬЦО_R} 0 0 1 ${КОЛЬЦО_R * 1.15} ${-КОЛЬЦО_R * 0.24}`}
        fill="none"
        stroke="#fff"
        strokeOpacity="0.75"
        strokeWidth="0.3"
        strokeLinecap="round"
      />
      {/* стык витка — по нему кольцо и опознаётся */}
      <path
        d={`M ${кольцоX + КОЛЬЦО_R * 0.62} ${cy - КОЛЬЦО_R * 0.78}
            a ${КОЛЬЦО_R} ${КОЛЬЦО_R} 0 0 0 ${-КОЛЬЦО_R * 0.62} ${-КОЛЬЦО_R * 0.22}`}
        fill="none"
        stroke="#55555c"
        strokeOpacity="0.5"
        strokeWidth="0.22"
      />
    </>
  );
}

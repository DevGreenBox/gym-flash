import { SPEC } from "@/lib/site";

/**
 * Силуэт корпуса — снят с чертежа заказчика пиксель в пиксель.
 *
 * Замер `assets/image 18.png`: корпус 287 × 99 px на 49,96 × 17 мм,
 * то есть 5,75 px/мм. Верх и низ идут ровной прямой от 282 до 532 px —
 * это плоские грани. Торцы выпирают ровно на 15 px = 2,6 мм и достигают
 * крайней точки на середине высоты. Значит торец — не полукруг
 * (радиус был бы 8,5 мм) и не скруглённый угол, а эллиптическая дуга:
 * 2,6 мм по горизонтали на 8,5 мм по вертикали.
 *
 * Такая же форма на фотографии партии — «подушка», а не капсула.
 *
 * Ширина колпачка замерена по той же фотографии: пластина 195 px
 * на 50 мм даёт 3,90 px/мм, чёрное слева — 5,4 мм.
 */
/**
 * Разъём USB. Флешка поворотная: цветная оболочка — внешняя часть,
 * чёрный разъём сидит внутри неё и выходит слева, а не приставлен
 * к торцу бруском, как было раньше.
 *
 * Числа — с крупного снимка заказчика от 27.08, он снят в лоб:
 * оболочка 307 px на 50 мм даёт 6,14 px/мм, чёрное выходит за торец
 * на 68 px = 11 мм. Высота проверяется тем же масштабом: 100 px
 * корпуса = 16,6 мм, то есть ракурса в снимке нет.
 *
 * Фотография партии (`assets/image 17.png`) даёт по той же оси
 * втрое меньше — 71 px при 23,04 px/мм, то есть 3,1 мм. Снимок
 * снят под углом и с другой партии; заказчик указал равняться
 * на крупный, там пропорции честные.
 */
const USB_ВЫЛЕТ = 11;
const USB_ПОЛЕ = 0.8;
const USB_НОС = 3;

/**
 * Левый предел надписи. На изделии «Ч» начинается примерно в 5,4 мм
 * от торца оболочки — дальше скруглённый нос, гравировать там нечего.
 * Число замерено по той же фотографии.
 */
export const ОТСТУП_НАДПИСИ = 5.4;

/** Вылет торца оболочки по горизонтали. */
const КРАЙ = 2.6;
const ПОЛЕ = 1;

export const ПЛАСТИНА_X = ПОЛЕ + USB_ВЫЛЕТ;
export const ПЛАСТИНА_Y = ПОЛЕ;

/**
 * Холст под флешку — ровно по нарисованному, поле в миллиметр
 * со всех сторон. Слева к оболочке добавляется вылет разъёма.
 */
export const ХОЛСТ = {
  w: USB_ВЫЛЕТ + SPEC.plate + ПОЛЕ * 2,
  h: SPEC.plateH + ПОЛЕ * 2,
};

/** Доли корпуса внутри холста — по ним кладутся зоны нажатия. */
export const ПЛАСТИНА_ДОЛИ = {
  left: (ПЛАСТИНА_X / ХОЛСТ.w) * 100,
  top: (ПЛАСТИНА_Y / ХОЛСТ.h) * 100,
  width: (SPEC.plate / ХОЛСТ.w) * 100,
  height: (SPEC.plateH / ХОЛСТ.h) * 100,
};

/** Контур корпуса: прямые верх и низ, торцы — эллиптические дуги. */
export const КОРПУС_D = (() => {
  const x = ПЛАСТИНА_X;
  const y = ПЛАСТИНА_Y;
  const w = SPEC.plate;
  const h = SPEC.plateH;
  const ry = h / 2;
  return [
    `M ${x + КРАЙ} ${y}`,
    `H ${x + w - КРАЙ}`,
    `A ${КРАЙ} ${ry} 0 0 1 ${x + w - КРАЙ} ${y + h}`,
    `H ${x + КРАЙ}`,
    `A ${КРАЙ} ${ry} 0 0 1 ${x + КРАЙ} ${y}`,
    "Z",
  ].join(" ");
})();

/**
 * Чёрный разъём. Рисуется под оболочкой, поэтому виден только его вылет:
 * оболочка накрывает остальное своим скруглённым носом — ровно тот стык,
 * что видно на изделии. Форма та же, что у корпуса: прямые верх и низ,
 * торец эллиптической дугой.
 */
export function DriveUSB({ uid }: { uid: string }) {
  const x = ПЛАСТИНА_X - USB_ВЫЛЕТ;
  const y = ПЛАСТИНА_Y + USB_ПОЛЕ;
  const h = SPEC.plateH - USB_ПОЛЕ * 2;
  const ry = h / 2;
  /* правый край уводим глубоко под оболочку — там он всё равно скрыт */
  const x1 = ПЛАСТИНА_X + 8;
  const d = [
    `M ${x + USB_НОС} ${y}`,
    `H ${x1}`,
    `V ${y + h}`,
    `H ${x + USB_НОС}`,
    `A ${USB_НОС} ${ry} 0 0 1 ${x + USB_НОС} ${y}`,
    "Z",
  ].join(" ");

  return (
    <>
      <defs>
        <linearGradient id={`${uid}-usb`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor="#4a4a4d" />
          <stop offset="38%" stopColor="#292a2c" />
          <stop offset="100%" stopColor="#141416" />
        </linearGradient>
      </defs>
      <path d={d} fill={`url(#${uid}-usb)`} />
    </>
  );
}

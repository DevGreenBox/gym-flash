import { SPEC } from "@/lib/site";

/**
 * Корпус поворотной флешки, вектором.
 *
 * Прежняя модель была «плашкой»: цельный брусок, пластина утоплена
 * в металлическую рамку. У заказчика поворотная — пластина со скруглёнными
 * торцами ходит вокруг оси в чёрном корпусе, на дальнем конце сквозь неё
 * продето кольцо.
 *
 * Размеры пластины из чертежа: 50 × 17, торцы скруглены по половине
 * высоты — на фотографиях они полукруглые. Корпус и кольцо сняты
 * с наклонных снимков на глаз.
 *
 * TODO(client): кадры анфас — уточнить корпус и кольцо.
 */
/* Замерено по фотографии партии (`assets/image 17.png`, красная флешка):
   пластина 195 px на 50 мм, то есть 3,90 px/мм; чёрный колпачок слева —
   5,4 мм, и высота у него та же, что у пластины. Прежняя модель делала
   его вдвое шире и выше. */
const КОРПУС_Ш = 5.4;
const НАХЛЁСТ = 0.8;
const КОЛЬЦО_R = 2.2;
const ПОЛЕ = 1;

/** Пластина внутри холста. */
export const ПЛАСТИНА_X = КОРПУС_Ш - НАХЛЁСТ;
export const ПЛАСТИНА_Y = ПОЛЕ;

export const ХОЛСТ = {
  w: ПЛАСТИНА_X + SPEC.plate + КОЛЬЦО_R * 2 + 0.8,
  h: SPEC.plateH + ПОЛЕ * 2,
};

const КОЛЬЦО_X = ПЛАСТИНА_X + SPEC.plate + КОЛЬЦО_R - 1.4;

/**
 * Доли пластины внутри холста — по ним конструктор кладёт поверх металла
 * прозрачные зоны нажатия. Считаются здесь, чтобы разметка и отрисовка
 * не разъезжались: раньше зоны брались от старой картинки и после смены
 * модели указывали мимо.
 */
export const ПЛАСТИНА_ДОЛИ = {
  left: (ПЛАСТИНА_X / ХОЛСТ.w) * 100,
  top: (ПЛАСТИНА_Y / ХОЛСТ.h) * 100,
  width: (SPEC.plate / ХОЛСТ.w) * 100,
  height: (SPEC.plateH / ХОЛСТ.h) * 100,
};

export function DriveBody({
  uid,
  chain = true,
}: {
  uid: string;
  /** false — без кольца: в мелких превью оно съедает ширину */
  chain?: boolean;
}) {
  const серединаY = ПОЛЕ + SPEC.plateH / 2;

  return (
    <>
      <defs>
        <linearGradient id={`${uid}-body`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor="#4c4c4f" />
          <stop offset="40%" stopColor="#2b2b2d" />
          <stop offset="100%" stopColor="#151516" />
        </linearGradient>
        <linearGradient id={`${uid}-ring`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor="#ececed" />
          <stop offset="52%" stopColor="#98989c" />
          <stop offset="100%" stopColor="#cdcdd1" />
        </linearGradient>
      </defs>

      {/* Кольцо продето в отверстие на дальнем конце пластины, поэтому
          частью уходит под неё — рисуем до пластины. */}
      {chain ? (
        <circle
          cx={КОЛЬЦО_X}
          cy={серединаY}
          r={КОЛЬЦО_R}
          fill="none"
          stroke={`url(#${uid}-ring)`}
          strokeWidth="0.8"
        />
      ) : null}

      {/* Чёрный корпус: пластина ходит вокруг оси внутри него, поэтому
          он чуть выше её и заходит под неё справа. */}
      <rect
        x={0}
        y={ПОЛЕ}
        width={КОРПУС_Ш + НАХЛЁСТ}
        height={SPEC.plateH}
        rx={2.4}
        fill={`url(#${uid}-body)`}
      />
    </>
  );
}

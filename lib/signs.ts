import КАРТА from "@/lib/signs.json";

/**
 * Пиктограммы-файлы для Зоны 2 (`public/signs/`).
 *
 * Гимнастические — исходники заказчика из «пиктограммы и обратная
 * сторона.pdf» (собирает `scripts/prepare-signs.py`); учёба и подарок —
 * нарисованы нами в их стиле (`scripts/draw-signs.mjs`). Подпись у всех
 * уже внутри рисунка, отдельной строки под знаком не нужно.
 *
 * У каждого знака два файла:
 *   <id>.png — для металла: белый знак с тенью гравировки, готовым
 *              растром — векторные контуры заказчика слишком подробны,
 *              чтобы перерисовывать их на каждой флешке галереи;
 *   <id>.svg — вектор без тени: маска в окне выбора знака.
 *
 * Рамка файла — ровно Зона 2, 11,5 × 15 мм: заказчик ставил знаки
 * «в границах», как они лягут на пластину. `signs.json` пишет скрипт:
 * где лежит растр относительно рамки, в долях рамки. Ниже рамки растр
 * длиннее на тень, у «Обруча» — ещё и на хвост «р».
 *
 * Знака «Для тренировок» в файле нет — у него остаётся прежний
 * рисунок из `components/icons.tsx` с подписью.
 */
export type SignBox = { x: number; y: number; w: number; h: number };

const МЕСТА: Record<string, SignBox> = КАРТА;

export const signArt = (id: string | null) =>
  id && id in МЕСТА ? { png: `/signs/${id}.png`, box: МЕСТА[id] } : null;

export const signFile = (id: string | null) =>
  id && id in МЕСТА ? `/signs/${id}.svg` : null;
